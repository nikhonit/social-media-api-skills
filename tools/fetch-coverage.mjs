#!/usr/bin/env node
/**
 * Derives `tools/coverage.json` from the live public OpenAPI spec.
 *
 * Every factual claim in this repo — which platforms exist, which endpoints are
 * callable, what they cost, what they take as input — comes from here. Nothing
 * about the API surface is typed by hand, because hand-typed tables go stale and
 * the stale copy is the one users read.
 *
 * The spec is public and needs no API key, so CI can re-run this and fail the
 * build when the repo's claims drift from the live API.
 *
 *   node tools/fetch-coverage.mjs           # refresh coverage.json
 *   node tools/fetch-coverage.mjs --check   # fail if coverage.json is stale
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SPEC_URL = 'https://scrapersocial.com/openapi.json';
const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'coverage.json');

/**
 * Buckets under /v1/ that describe the API itself rather than reading a
 * platform. They are deliberately excluded: they get no skill, and they are not
 * counted in the "N endpoints across N platforms" claim.
 */
const NON_PLATFORM = new Set(['meta', 'jobs', 'me', 'usage', 'webhooks']);

/** "Costs 2 credit(s) per post." -> { credits: 2, unit: 'post', note: null } */
function parseCredits(description = '') {
  const m = description.match(/Costs\s+(\d+)\s+credit\(s\)(?:\s+per\s+([^.]+))?\./i);
  if (!m) return null;
  let unit = m[2] ? m[2].trim() : 'call';
  let note = null;
  // e.g. "profile (25 with include_email=true)"
  const paren = unit.match(/^(.*?)\s*\((.+)\)\s*$/);
  if (paren) {
    unit = paren[1].trim();
    note = paren[2].trim();
  }
  return { credits: Number(m[1]), unit, note };
}

/**
 * The input kind decides which argument a script takes. `url|handle` endpoints
 * accept either, so neither parameter is marked required in the spec.
 */
function parseInput(parameters = []) {
  const names = new Set(parameters.map((p) => p.name));
  const required = parameters.filter((p) => p.required).map((p) => p.name);
  if (required.includes('url')) return 'url';
  if (required.includes('handle')) return 'handle';
  if (required.includes('query')) return 'query';
  if (names.has('url') && names.has('handle')) return 'url|handle';
  if (names.has('url')) return 'url';
  if (names.has('handle')) return 'handle';
  if (names.has('query')) return 'query';
  return 'none';
}

function buildCoverage(spec) {
  const platforms = {};
  let endpointCount = 0;

  for (const [path, item] of Object.entries(spec.paths || {})) {
    if (!path.startsWith('/v1/')) continue;
    const parts = path.split('/'); // ['', 'v1', platform, capability]
    if (parts.length !== 4) continue;
    const [, , platform, capability] = parts;
    if (NON_PLATFORM.has(platform)) continue;

    const op = item.get;
    if (!op) continue;

    const cost = parseCredits(op.description);
    if (!cost) {
      throw new Error(
        `No credit cost found for ${path}. The spec's description format changed; ` +
          `fix parseCredits() rather than guessing a number.`
      );
    }

    const parameters = op.parameters || [];
    const names = new Set(parameters.map((p) => p.name));

    (platforms[platform] ||= []).push({
      capability,
      path,
      input: parseInput(parameters),
      unit: cost.unit,
      credits: cost.credits,
      creditNote: cost.note,
      list: names.has('limit') && names.has('cursor'),
      supportsIncludeEmail: names.has('include_email'),
      summary: (op.summary || '').trim(),
    });
    endpointCount += 1;
  }

  // Deterministic ordering, so `--check` diffs mean drift and never key order.
  const sorted = {};
  for (const platform of Object.keys(platforms).sort()) {
    sorted[platform] = platforms[platform].sort((a, b) =>
      a.capability.localeCompare(b.capability)
    );
  }

  return {
    source: SPEC_URL,
    note:
      'Generated by tools/fetch-coverage.mjs from the live public OpenAPI spec. ' +
      'Do not edit by hand. Endpoints that are gated upstream never appear in the ' +
      'published spec, so everything listed here is callable today.',
    platformCount: Object.keys(sorted).length,
    endpointCount,
    platforms: sorted,
  };
}

function serialize(coverage) {
  return JSON.stringify(coverage, null, 2) + '\n';
}

const res = await fetch(SPEC_URL, { headers: { accept: 'application/json' } });
if (!res.ok) {
  console.error(`Failed to fetch ${SPEC_URL}: HTTP ${res.status}`);
  process.exit(1);
}
const coverage = buildCoverage(await res.json());
const next = serialize(coverage);

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== next) {
    console.error(
      'coverage.json is out of date with the live API.\n' +
        `Live spec now has ${coverage.endpointCount} endpoints across ${coverage.platformCount} platforms.\n` +
        'Run: node tools/fetch-coverage.mjs && node tools/generate.mjs'
    );
    process.exit(1);
  }
  console.log(
    `coverage.json matches the live API: ${coverage.endpointCount} endpoints across ${coverage.platformCount} platforms.`
  );
} else {
  writeFileSync(OUT, next);
  console.log(
    `Wrote ${OUT}: ${coverage.endpointCount} endpoints across ${coverage.platformCount} platforms.`
  );
}
